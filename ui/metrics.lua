ui/metrics.lua -- advance widths for the panel's font, as fractions of the em.

GENERATED by tools/genmetrics.py from the installed TrueType files. Do not edit
by hand; regenerate.

Why it exists. Proportional type has no single advance number, and
`windower.text.get_extents` cannot carry layout: it only answers about a string
an object has already been given, which is a frame too late to decide how to wrap
that string, and it cannot answer at all about a string you have not drawn.

Indexed by byte, 32..126, because the panel is single-byte ASCII only: Windower's
text rendering does not handle UTF-8 multibyte. A byte outside that range falls
through the metatable to the average advance, so a stray character costs a
slightly wrong wrap and never an error.

Measured, not estimated. Segoe UI Regular averages 0.5136 em across printable
ASCII and Consolas averages 0.5498, so a monospace constant taken from Consolas
over-estimates every proportional string by about 7%. That direction only wastes
space; the units error is the one that runs text off the panel.
]]

