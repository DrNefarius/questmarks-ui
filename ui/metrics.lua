local function guard(t, avg)
    return setmetatable(t, {__index = function() return avg end})
end
guard(M.regular, M.avg_regular)
guard(M.bold, M.avg_bold)

--[[ Width of `s` in pixels at `pt` points.

     The 2% slack covers hinting. The rasteriser rounds each glyph advance to a
     whole pixel at screen sizes, and over 50 characters those roundings do not
     cancel. Over-estimating is the safe direction: it wraps a word one early,
     where under-estimating runs text off the panel. ]]
function M.width(s, pt, bold)
    if type(s) ~= 'string' or s == '' then return 0 end
    local t = bold and M.bold or M.regular
    local sum = 0
    for i = 1, #s do sum = sum + t[s:byte(i)] end
    return sum * pt * M.PT_TO_PX * 1.02
end

--[[ How many characters of `s` fit in `px`. Walks the string rather than
     dividing by an average, because "Ill" and "WWW" are not the same width. ]]
function M.fit_count(s, pt, px, bold)
    local t = bold and M.bold or M.regular
    local k = pt * M.PT_TO_PX * 1.02
    local sum, n = 0, 0
    for i = 1, #s do
        sum = sum + t[s:byte(i)] * k
        if sum > px then return n end
        n = i
    end
    return n
end

--[[ Vertical geometry in pixels at a point size.

     `set_location` places text by the top of its line box. `ink_y` is how far
     below that the glyphs actually begin and `ink_height` is how tall they are,
     and together they are the rectangle to highlight or to hit-test. Size a
     hover band from the line pitch instead and it draws about seven pixels above
     its own text. ]]
function M.ink_y(pt)      return pt * M.PT_TO_PX * M.ink_top end
function M.ink_height(pt) return pt * M.PT_TO_PX * M.ink_h end
function M.line_height(pt) return pt * M.PT_TO_PX * M.line_h end

--[[ The y to draw at so the cap box is centred in a strip of height `h` starting
     at `y`. Cap-centred rather than ink-centred: most interface strings carry no
     descender, so centring the full ink box makes them ride visibly high. ]]
function M.center_y(y, h, pt)
    local em = pt * M.PT_TO_PX
    return math.floor(y + h / 2 - (M.cap_top + M.cap_h / 2) * em + 0.5)
end

--[[ Where an underline goes: just below the descender. ]]
function M.underline_y(y, pt)
    return math.floor(y + (M.ink_top + M.ink_h) * pt * M.PT_TO_PX + 0.5)
end

return M
